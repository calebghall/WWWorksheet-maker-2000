#!/usr/bin/env python3
"""Embed the crosswalks: standards/<fw>.crosswalk.json -> src/js/core/standards-xw.js (generated; build.py runs this).
Row: { "to": [preset ids], "status": "supported" | "partial" | "gap", "note": (partial), "need": (gap) }.
A row with `to` builds that preset (several ids build a Combined worksheet); a gap row has no `to`.
Checks: every row's status is valid, partial has a note, gap has a need and no `to`, others have `to`;
every id in `to` exists in src/js/core/standards.js; every code is a row of standards/<fw>.json."""
import glob, json, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
ids = set(re.findall(r"\{ id: '([^']+)'", open(root + 'src/js/core/standards.js', encoding='utf-8').read()))
out, errs = {}, []
for path in sorted(glob.glob(root + 'standards/*.crosswalk.json')):
    fw = os.path.basename(path).split('.')[0]
    xw = json.load(open(path, encoding='utf-8'))
    rows = json.load(open(root + f'standards/{fw}.json', encoding='utf-8'))['rows']
    if xw.get('framework') != fw: errs.append(f'{fw}: framework field {xw.get("framework")}')
    for code in rows:
        if code not in xw['rows']: errs.append(f'{fw} {code}: no crosswalk row')
    for code, r in xw['rows'].items():
        if code not in rows: errs.append(f'{fw} {code}: not a standard of the framework')
        st = r.get('status'); to = r.get('to') or []
        if st not in ('supported', 'partial', 'gap'): errs.append(f'{fw} {code}: status {st}')
        if st == 'gap' and (to or not r.get('need')): errs.append(f'{fw} {code}: a gap row has a need and no to')
        if st != 'gap' and not to: errs.append(f'{fw} {code}: needs to')
        if st == 'partial' and not r.get('note'): errs.append(f'{fw} {code}: partial needs a note')
        for i in to:
            if i not in ids: errs.append(f'{fw} {code}: unknown preset id {i}')
    out[fw] = xw['rows']
if errs: sys.exit('\n'.join(errs))
open(root + 'src/js/core/standards-xw.js', 'w', encoding='utf-8').write(
    '/* Generated by tools/build_xw.py from standards/*.crosswalk.json. Do not edit. */\nconst STD_XW = '
    + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
print('crosswalks', {fw: len(r) for fw, r in out.items()})
