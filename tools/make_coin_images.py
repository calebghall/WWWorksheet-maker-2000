"""Downsize the US Mint coin photos and embed them in src/js/modules/coin-images.js.
Usage: python3 tools/make_coin_images.py DIR   (DIR holds penny.jpg, nickel.jpg, dime.jpg, quarter.jpg, any size)
Each coin is cropped to its circle, resized to SIZE px, and saved twice: color and greyscale (assets/coins/NAME.jpg, NAME-grey.jpg).
The greyscale copy darkens the copper penny so it stays clearly different from the silver coins when printed in black and white.
Images are United States Mint coin images (public domain). Needs Pillow and numpy."""
import sys, os, io, base64
import numpy as np
from PIL import Image, ImageDraw
SIZE, Q = 256, 72
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
src = sys.argv[1].rstrip('/') + '/'
os.makedirs(root + 'assets/coins', exist_ok=True)
def prep(name):
    im = Image.open(src + name + '.jpg').convert('RGB')
    a = np.asarray(im.convert('L')) < 245
    ys, xs = np.where(a)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    cx, cy, r = (x0 + x1) / 2, (y0 + y1) / 2, max(x1 - x0, y1 - y0) / 2
    im = im.crop((int(cx - r), int(cy - r), int(cx + r), int(cy + r))).resize((SIZE * 2, SIZE * 2), Image.LANCZOS)
    mask = Image.new('L', im.size, 0); ImageDraw.Draw(mask).ellipse((0, 0, im.size[0] - 1, im.size[1] - 1), fill=255)
    bg = Image.new('RGB', im.size, (255, 255, 255)); bg.paste(im, mask=mask)
    return bg.resize((SIZE, SIZE), Image.LANCZOS)
def jpg(im):
    b = io.BytesIO(); im.save(b, 'JPEG', quality=Q, optimize=True, progressive=True); return b.getvalue()
out = {}
for name in ['penny', 'nickel', 'dime', 'quarter']:
    c = prep(name); g = c.convert('L')
    if name == 'penny':   # copper is mid-bright in grey; darken the coin disc only so it separates from silver
        arr = np.asarray(g).astype(float); m = arr < 250; arr[m] = arr[m] * 0.78; g = Image.fromarray(arr.astype('uint8'))
    cb, gb = jpg(c), jpg(g.convert('RGB') if False else g)
    open(root + f'assets/coins/{name}.jpg', 'wb').write(cb); open(root + f'assets/coins/{name}-grey.jpg', 'wb').write(gb)
    out[name] = ('data:image/jpeg;base64,' + base64.b64encode(cb).decode(), 'data:image/jpeg;base64,' + base64.b64encode(gb).decode())
    print(name, len(cb), len(gb))
js = '/* Generated by tools/make_coin_images.py from United States Mint coin images (public domain). Do not edit by hand. */\nconst COIN_IMG = {\n'
js += ',\n'.join(f"  {k}: {{ c: '{v[0]}', g: '{v[1]}' }}" for k, v in out.items()) + '\n};\n'
open(root + 'src/js/modules/coin-images.js', 'w').write(js)
print('coin-images.js', len(js))
